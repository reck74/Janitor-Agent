def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="honcho_setup.py", description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("preflight", help="Read-only: what is feasible and what is missing")
    p.add_argument("--port", type=int)
    p = sub.add_parser("deploy", help="Local mode: deploy or repair the janitor-honcho-* containers")
    p.add_argument("--port", type=int)
    p.add_argument("--llm", choices=("auto", "openai", "minimax"), default="auto")
    p.add_argument("--timeout", type=float, default=240, help="seconds to wait for /health after up")
    p.add_argument("--build-timeout", type=float, default=1800, help="seconds for docker compose up (build)")
    p.add_argument("--interval", type=float, default=3, help=argparse.SUPPRESS)
    p = sub.add_parser("cloud-login", help="Cloud mode: device-code sign-in (no secret in chat)")
    for name in ("verify", "activate"):
        p = sub.add_parser(name)
        p.add_argument("--mode", choices=("local", "cloud"), required=(name == "activate"))
        p.add_argument("--port", type=int)
        p.add_argument("--peer-name")
    p = sub.add_parser("rollback", help="Restore the previous memory provider (keeps all data)")
    p.add_argument("--stop-containers", action="store_true")
    return parser


COMMANDS = {"preflight": cmd_preflight, "deploy": cmd_deploy, "cloud-login": cmd_cloud_login,
            "verify": cmd_verify, "activate": cmd_activate, "rollback": cmd_rollback}
NEEDS_RUNTIME = {"cloud-login", "verify", "activate", "rollback"}


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    homes = resolve_homes()
    if homes is None:
        hint("HERMES_HOME no está definido: ejecútalo desde Janitor (terminal del agente).")
        finish({"command": args.command, "ok": False, "reason": "hermes_home_unset"})
        return 2
    os.environ["HERMES_HOME"] = str(homes.profile)
    if args.command in NEEDS_RUNTIME or args.command == "preflight":
        ensure_runtime()
    return COMMANDS[args.command](args, homes)


if __name__ == "__main__":
    raise SystemExit(main())
