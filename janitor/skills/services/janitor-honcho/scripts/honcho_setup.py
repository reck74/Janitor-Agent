# ── output ────────────────────────────────────────────────────────────────


class Redactor:
    """Replaces every known secret value with ``***`` in anything we print."""

    def __init__(self) -> None:
        self.values: set[str] = set()

    def add(self, *values: str | None) -> None:
        self.values.update(v for v in values if v and len(v) >= 6)

    def __call__(self, text: str) -> str:
        for value in sorted(self.values, key=len, reverse=True):
            text = text.replace(value, "***")
        return text


REDACT = Redactor()


def hint(message: str) -> None:
    print(REDACT(message), file=sys.stderr, flush=True)


def emit(doc: dict) -> None:
    print(REDACT(json.dumps(doc, ensure_ascii=False, indent=2, default=str)), flush=True)


def finish(doc: dict) -> int:
    doc.setdefault("schema_version", SCHEMA_VERSION)
    emit(doc)
    return 0 if doc.get("ok", True) else 1


def refuse(command: str, reason: str, **extra) -> int:
    return finish({"command": command, "ok": False, "reason": reason, **extra})


# ── homes, files, secrets ───────────────────────────────────────────────


class Homes:
    def __init__(self, profile: Path, root: Path) -> None:
        self.profile, self.root = profile, root
        self.deploy_dir = root / "docker"
        self.source_dir = root / "src" / "honcho"
        self.state_dir = profile / "janitor" / "honcho"
        self.state_file = self.state_dir / "state.json"
        self.env_file = profile / ".env"
        self.config_file = profile / "config.yaml"
        self.honcho_json = profile / "honcho.json"


def resolve_homes() -> Homes | None:
    raw = (os.environ.get("HERMES_HOME") or os.environ.get("JANITOR_HOME") or "").strip()
    if not raw:
        return None
    profile = Path(raw).expanduser()
    root_raw = (os.environ.get("JANITOR_HOME") or "").strip()
    if root_raw:
        root = Path(root_raw).expanduser()
    elif profile.parent.name == "profiles":
        root = profile.parent.parent
    else:
        root = profile
    return Homes(profile, root)


def read_env_file(path: Path) -> dict[str, str]:
    """Minimal dotenv reader (KEY=VALUE, optional ``export``, quotes). Values stay in memory."""
    values: dict[str, str] = {}
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError:
        return values
    for line in lines:
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        key = key.strip()
        if key.startswith("export "):
            key = key[len("export "):].strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        elif " #" in value:
            value = value.split(" #", 1)[0].rstrip()
        values[key] = value
    return values


def credentials(homes: Homes) -> dict[str, str]:
    """Profile .env first, then the process environment. Registers every value for redaction."""
    env_file = read_env_file(homes.env_file)
    merged = {name: (env_file.get(name) or os.environ.get(name) or "").strip() for name in CREDENTIAL_NAMES}
    REDACT.add(*(v for k, v in env_file.items() if is_secret_name(k)))
    REDACT.add(*(v for k, v in merged.items() if is_secret_name(k)))
    return merged


def is_secret_name(name: str) -> bool:
    upper = name.upper()
    return any(word in upper for word in SECRET_WORDS)


def sha256_file(path: Path) -> str | None:
    try:
        return hashlib.sha256(path.read_bytes()).hexdigest()
    except OSError:
        return None


def atomic_write(path: Path, data: bytes, mode: int = 0o600) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=str(path.parent), prefix=f".{path.name}.")
    try:
        with os.fdopen(fd, "wb") as fh:
            fh.write(data)
        os.chmod(tmp, mode)
        os.replace(tmp, path)
    except BaseException:
        with contextlib.suppress(OSError):
            os.unlink(tmp)
        raise


def timestamp() -> str:
    return _dt.datetime.now().strftime("%Y%m%d-%H%M%S")


def load_state(homes: Homes) -> dict:
    try:
        data = json.loads(homes.state_file.read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else {}
    except (OSError, ValueError):
        return {}


def save_state(homes: Homes, state: dict) -> None:
    atomic_write(homes.state_file, json.dumps(state, indent=2).encode("utf-8"))


# ── tools on PATH ───────────────────────────────────────────────────────


def which(name: str) -> str | None:
    """PATH lookup without shutil.which (an upstream guard scans janitor/ for it)."""
    for entry in os.environ.get("PATH", "").split(os.pathsep):
        if not entry:
            continue
        candidate = Path(entry) / name
        if candidate.is_file() and os.access(candidate, os.X_OK):
            return str(candidate)
    return None


def run(argv: list[str], *, timeout: float = 60, env: dict | None = None, cwd: str | None = None):
    try:
        return subprocess.run(argv, capture_output=True, text=True, timeout=timeout, env=env, cwd=cwd, check=False)
    except FileNotFoundError:
        return subprocess.CompletedProcess(argv, 127, "", f"{argv[0]}: not found")
    except subprocess.TimeoutExpired:
        return subprocess.CompletedProcess(argv, 124, "", f"{argv[0]}: timed out after {timeout}s")


def tail(text: str, lines: int = 30) -> list[str]:
    return [REDACT(line) for line in (text or "").splitlines()[-lines:]]


# ── probes (read-only) ──────────────────────────────────────────────────


def os_release() -> dict[str, str]:
    data: dict[str, str] = {}
    with contextlib.suppress(OSError):
        for line in Path("/etc/os-release").read_text(encoding="utf-8").splitlines():
            key, _, value = line.partition("=")
            data[key.strip()] = value.strip().strip('"')
    return data


def docker_install_hint() -> dict[str, str]:
    """Exact install command for the user to run. Suggestion only: never executed here."""
    if sys.platform == "darwin":
        return {"distro": "macos", "command": "brew install --cask docker  # o Docker Desktop: https://docs.docker.com/desktop/"}
    rel = os_release()
    ids = {rel.get("ID", "").lower(), *rel.get("ID_LIKE", "").lower().split()}
    distro = rel.get("ID", "linux") or "linux"
    group = "sudo usermod -aG docker $USER  # cierra sesión y vuelve a entrar"
    if "arch" in ids:
        cmd = f"sudo pacman -S --needed docker docker-compose && sudo systemctl enable --now docker.service && {group}"
    elif ids & {"opensuse", "suse", "sles"}:
        cmd = f"sudo zypper install docker docker-compose && sudo systemctl enable --now docker && {group}"
    else:  # Debian, Ubuntu, Fedora, CentOS, RHEL, Raspbian: Docker's convenience script
        cmd = f"curl -fsSL https://get.docker.com -o get-docker.sh && sudo sh get-docker.sh && {group}"
    return {"distro": distro, "command": cmd}


def probe_docker() -> dict:
    out = {"cli": False, "daemon": False, "compose_v2": False, "compose_version": None,
           "root_dir": None, "error": None, "install_hint": None, "fix_hint": None}
    if not which("docker"):
        out["error"] = "docker_missing"
        out["install_hint"] = docker_install_hint()
        return out
    out["cli"] = True
    info = run(["docker", "info", "--format", "{{.DockerRootDir}}"], timeout=20)
    if info.returncode != 0:
        err = (info.stderr or "").lower()
        if "permission denied" in err:
            out["error"] = "docker_permission_denied"
            out["fix_hint"] = "sudo usermod -aG docker $USER  # cierra sesión y vuelve a entrar"
        else:
            out["error"] = "docker_daemon_down"
            out["fix_hint"] = "sudo systemctl start docker"
    else:
        out["daemon"] = True
        out["root_dir"] = (info.stdout or "").strip() or None
    compose = run(["docker", "compose", "version", "--short"], timeout=20)
    if compose.returncode == 0 and (compose.stdout or "").strip():
        version = compose.stdout.strip().lstrip("v")
        out["compose_version"] = version
        out["compose_v2"] = version.split(".", 1)[0].isdigit() and int(version.split(".", 1)[0]) >= 2
    return out


def port_free(port: int) -> bool:
    sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    try:
        sock.bind(("127.0.0.1", port))
        return True
    except OSError:
        return False
    finally:
        sock.close()


def http_ok(url: str, timeout: float = 3.0) -> bool:
    try:
        with urllib.request.urlopen(url, timeout=timeout) as resp:  # noqa: S310 — loopback/cloud URL we built
            return 200 <= resp.status < 300
    except (urllib.error.URLError, OSError, ValueError):
        return False


def container_states(docker_ok: bool) -> dict[str, dict]:
    states: dict[str, dict] = {}
    for name in CONTAINERS:
        if not docker_ok:
            states[name] = {"status": "unknown", "health": None}
            continue
        proc = run(["docker", "inspect", "-f", "{{.State.Status}}|{{if .State.Health}}{{.State.Health.Status}}{{end}}", name])
        if proc.returncode != 0:
            states[name] = {"status": "absent", "health": None}
            continue
        status, _, health = (proc.stdout or "").strip().partition("|")
        states[name] = {"status": status or "unknown", "health": health or None}
    return states


def summarize(states: dict[str, dict]) -> str:
    values = {s["status"] for s in states.values()}
    if values == {"running"}:
        return "running"
    if values == {"absent"}:
        return "not deployed"
    if "unknown" in values:
        return "unknown"
    return "degraded" if "running" in values else "stopped"


def docker_objects(docker_ok: bool) -> tuple[dict[str, bool | None], bool | None]:
    if not docker_ok:
        return {v: None for v in VOLUMES}, None
    volumes = {v: run(["docker", "volume", "inspect", v]).returncode == 0 for v in VOLUMES}
    network = run(["docker", "network", "inspect", NETWORK]).returncode == 0
    return volumes, network


def disk_free(paths: list[Path]) -> dict:
    for path in paths:
        probe = path
        while not probe.exists() and probe != probe.parent:
            probe = probe.parent
        try:
            usage = shutil.disk_usage(probe)
        except OSError:
            continue
        free_gb = round(usage.free / 1024 ** 3, 1)
        return {"path": str(probe), "free_gb": free_gb, "required_gb": MIN_FREE_GB, "enough": free_gb >= MIN_FREE_GB}
    return {"path": None, "free_gb": None, "required_gb": MIN_FREE_GB, "enough": None}


def compose_status(homes: Homes) -> dict:
    deployed = homes.deploy_dir / COMPOSE_NAME
    digest = sha256_file(deployed)
    if digest is None:
        return {"deployed": False, "owner": None}
    stamp = (homes.deploy_dir / STAMP_NAME)
    ours = digest == sha256_file(SHIPPED_COMPOSE) or digest in LEGACY_COMPOSE_SHA256 or (
        stamp.is_file() and stamp.read_text(encoding="utf-8").strip() == digest)
    return {"deployed": True, "owner": "janitor" if ours else "user"}


def llm_env_status(homes: Homes) -> str:
    path = homes.deploy_dir / LLM_ENV_NAME
    try:
        first = path.read_text(encoding="utf-8").splitlines()[:1]
    except OSError:
        return "absent"
    return "generated" if first == [LLM_ENV_MARKER] else "user"


def deriver_plan(creds: dict[str, str], env_owner: str) -> dict:
    """Which credentials the deriver/API containers would use (presence only)."""
    openai = bool(creds["OPENAI_API_KEY"] or creds["LLM_OPENAI_API_KEY"])
    minimax = bool(creds["MINIMAX_API_KEY"] or creds["LLM_ANTHROPIC_API_KEY"])
    if env_owner == "user":
        return {"profile": "user-managed", "llm": True, "embeddings": True, "source": LLM_ENV_NAME}
    if minimax and openai:
        return {"profile": "minimax", "llm": True, "embeddings": True, "source": "MINIMAX_API_KEY + OPENAI_API_KEY"}
    if openai:
        return {"profile": "openai", "llm": True, "embeddings": True, "source": "OPENAI_API_KEY"}
    if minimax:
        return {"profile": "minimax", "llm": True, "embeddings": False, "source": "MINIMAX_API_KEY"}
    return {"profile": None, "llm": False, "embeddings": False, "source": None}


def read_user_config(homes: Homes) -> tuple[dict | None, str | None]:
    """Raw config.yaml (not merged with defaults). (None, reason) when it cannot be read."""
    if not homes.config_file.exists():
        return {}, None
    try:
        import yaml
    except ImportError:
        return None, "pyyaml_unavailable"
    try:
        data = yaml.safe_load(homes.config_file.read_text(encoding="utf-8")) or {}
    except (OSError, yaml.YAMLError) as exc:
        return None, f"config_unreadable: {exc.__class__.__name__}"
    return (data if isinstance(data, dict) else {}), None


def memory_provider(cfg: dict | None) -> tuple[str | None, bool]:
    """(provider, present). Missing key or empty string = built-in memory."""
    if cfg is None:
        return None, False
    memory = cfg.get("memory")
    if not isinstance(memory, dict) or "provider" not in memory:
        return "", False
    return str(memory.get("provider") or ""), True


def configured_port(cfg: dict | None) -> int:
    for path in (("skills", "config", "janitor", "honcho_port"), ("skills", "config", "janitor.honcho_port"),
                 ("janitor", "honcho_port")):
        node = cfg or {}
        for key in path:
            node = node.get(key) if isinstance(node, dict) else None
        if isinstance(node, int) and 0 < node < 65536:
            return node
    return DEFAULT_PORT


def honcho_json_status(homes: Homes) -> dict:
    """Upstream resolution order: $HERMES_HOME/honcho.json > default profile > ~/.honcho/config.json."""
    candidates = [homes.honcho_json]
    default_profile = homes.root / "honcho.json"
    if default_profile != homes.honcho_json:
        candidates.append(default_profile)
    candidates.append(Path.home() / ".honcho" / "config.json")
    listed = [{"path": str(p), "exists": p.is_file()} for p in candidates]
    resolved = next((p for p in candidates if p.is_file()), None)
    out = {"candidates": listed, "resolved": str(resolved) if resolved else None,
           "profile_file_exists": homes.honcho_json.is_file(), "parseable": None,
           "base_url": None, "has_api_key": False, "has_oauth": False}
    if resolved:
        try:
            raw = json.loads(resolved.read_text(encoding="utf-8"))
            out["parseable"] = isinstance(raw, dict)
        except (OSError, ValueError):
            out["parseable"] = False
            raw = {}
        if isinstance(raw, dict):
            blocks = [raw, *[b for b in (raw.get("hosts") or {}).values() if isinstance(b, dict)]]
            out["base_url"] = next((b.get("baseUrl") for b in blocks if b.get("baseUrl")), None)
            out["has_api_key"] = any(bool(b.get("apiKey")) for b in blocks)
            out["has_oauth"] = any(isinstance(b.get("oauth"), dict) for b in blocks)
            REDACT.add(*(str(b.get("apiKey")) for b in blocks if b.get("apiKey")))
            for b in blocks:
                if isinstance(b.get("oauth"), dict):
                    REDACT.add(*(str(v) for v in b["oauth"].values() if isinstance(v, str)))
    return out


# ── preflight ───────────────────────────────────────────────────────────


def cmd_preflight(args, homes: Homes) -> int:
    cfg, cfg_error = read_user_config(homes)
    port = args.port or configured_port(cfg)
    creds = credentials(homes)
    docker = probe_docker()
    docker_ok = docker["daemon"]
    states = container_states(docker_ok)
    volumes, network = docker_objects(docker_ok)
    service_state = summarize(states)
    url = f"http://127.0.0.1:{port}"
    api_healthy = http_ok(f"{url}/health") if states["janitor-honcho-api"]["status"] == "running" else False
    free = port_free(port)
    owner = None if free else ("janitor-honcho-api" if states["janitor-honcho-api"]["status"] == "running" else "other")
    env_owner = llm_env_status(homes)
    deriver = deriver_plan(creds, env_owner)
    provider, provider_present = memory_provider(cfg)
    hjson = honcho_json_status(homes)
    state = load_state(homes)
    disk = disk_free(([Path(docker["root_dir"])] if docker["root_dir"] else []) + [homes.root])
    source_present = (homes.source_dir / "Dockerfile").is_file()

    local_blockers = []
    if docker["error"]:
        local_blockers.append(docker["error"])
    elif not docker["compose_v2"]:
        local_blockers.append("compose_v2_missing")
    if owner == "other":
        local_blockers.append("port_busy")
    if disk["enough"] is False and service_state == "not deployed":
        local_blockers.append("disk_low")
    if not source_present and not which("git") and service_state == "not deployed":
        local_blockers.append("git_missing")
    if service_state == "not deployed" or env_owner == "absent":
        if not deriver["llm"]:
            local_blockers.append("llm_credential_missing")
        elif not deriver["embeddings"]:
            local_blockers.append("embeddings_credential_missing")

    cloud_credential = "api_key" if creds["HONCHO_API_KEY"] else ("oauth" if hjson["has_oauth"] else "none")
    runtime = hermes_runtime_available()
    already_active = provider == "honcho"
    if already_active:
        recommendation = "already-active"
    elif not local_blockers:
        recommendation = "local"
    else:
        recommendation = "cloud"

    doc = {
        "command": "preflight", "ok": True,
        "home": {"profile": str(homes.profile), "root": str(homes.root), "deploy_dir": str(homes.deploy_dir)},
        "docker": docker,
        "port": {"number": port, "free": free, "owner": owner},
        "disk": disk,
        "service": {
            "state": service_state, "url": url, "api_healthy": api_healthy, "containers": states,
            "volumes": volumes, "network": network,
            "compose": compose_status(homes), "llm_env": env_owner, "source_present": source_present,
        },
        "memory": {"provider": provider, "provider_set": provider_present, "config_path": str(homes.config_file),
                   "config_error": cfg_error, "built_in": provider == ""},
        "honcho_json": hjson,
        "credentials": {name: bool(value) for name, value in creds.items()},
        "deriver": deriver,
        "activation_record": {"present": bool(state.get("activated_at")), "mode": state.get("mode"),
                              "rolled_back": bool(state.get("rolled_back_at"))},
        "hermes_runtime": runtime,
        "modes": {
            "local": {"feasible": not local_blockers, "blockers": local_blockers},
            "cloud": {"feasible": runtime, "credential": cloud_credential,
                      "blockers": [] if runtime else ["hermes_runtime_missing"]},
        },
        "recommendation": recommendation,
    }
    for blocker in local_blockers:
        hint(f"local: bloqueado por {blocker}")
    return finish(doc)


# ── deploy (mode B) ─────────────────────────────────────────────────────


def ensure_compose(homes: Homes) -> str:
    deployed = homes.deploy_dir / COMPOSE_NAME
    stamp = homes.deploy_dir / STAMP_NAME
    shipped = SHIPPED_COMPOSE.read_bytes()
    shipped_sha = hashlib.sha256(shipped).hexdigest()
    status = compose_status(homes)
    if status["deployed"] and status["owner"] == "user":
        hint(f"{deployed} tiene cambios del usuario: se conserva tal cual.")
        return "kept-user-file"
    if status["deployed"] and sha256_file(deployed) == shipped_sha:
        atomic_write(stamp, shipped_sha.encode(), 0o644)
        return "unchanged"
    if status["deployed"]:
        backup = homes.deploy_dir / f"{COMPOSE_NAME}.bak-{timestamp()}"
        shutil.copy2(deployed, backup)
        hint(f"Compose anterior respaldado en {backup}")
    atomic_write(deployed, shipped, 0o644)
    atomic_write(stamp, shipped_sha.encode(), 0o644)
    return "updated" if status["deployed"] else "installed"


def ensure_source(homes: Homes) -> tuple[str, dict | None]:
    if (homes.source_dir / "Dockerfile").is_file():
        return "present", None
    if homes.source_dir.exists() and any(homes.source_dir.iterdir()):
        return "failed", {"reason": "source_dir_not_honcho", "path": str(homes.source_dir)}
    homes.source_dir.parent.mkdir(parents=True, exist_ok=True)
    hint(f"Clonando Honcho ({HONCHO_GIT_SHA[:12]}) en {homes.source_dir} ...")
    clone = run(["git", "clone", "--quiet", HONCHO_GIT_URL, str(homes.source_dir)], timeout=600)
    if clone.returncode != 0:
        return "failed", {"reason": "git_clone_failed", "log": tail(clone.stderr)}
    checkout = run(["git", "-C", str(homes.source_dir), "checkout", "--quiet", HONCHO_GIT_SHA], timeout=120)
    if checkout.returncode != 0:
        return "failed", {"reason": "git_checkout_failed", "log": tail(checkout.stderr)}
    return "cloned", None


def llm_env_lines(homes: Homes, profile: str) -> list[str]:
    env = read_env_file(homes.env_file)

    def pick(*names: str) -> str:
        return next(((env.get(n) or os.environ.get(n) or "").strip() for n in names
                     if (env.get(n) or os.environ.get(n) or "").strip()), "")

    openai_key = pick("OPENAI_API_KEY", "LLM_OPENAI_API_KEY")
    lines = [LLM_ENV_MARKER, "# Solo las credenciales que Honcho necesita. Regenerado por cada deploy.", "AUTH_USE_AUTH=false"]
    if openai_key:
        lines.append(f"LLM_OPENAI_API_KEY={openai_key}")
    if profile == "minimax":
        lines += [f"LLM_ANTHROPIC_API_KEY={pick('MINIMAX_API_KEY', 'LLM_ANTHROPIC_API_KEY')}",
                  f"LLM_ANTHROPIC_BASE_URL={MINIMAX_ANTHROPIC_URL}"]
        for feature in MINIMAX_FEATURES:
            lines += [f"{feature}_MODEL_CONFIG__TRANSPORT=anthropic", f"{feature}_MODEL_CONFIG__MODEL={MINIMAX_MODEL}"]
    return lines


def ensure_llm_env(homes: Homes, profile: str) -> str:
    owner = llm_env_status(homes)
    if owner == "user":
        hint(f"{homes.deploy_dir / LLM_ENV_NAME} es del usuario: se conserva tal cual.")
        return "kept-user-file"
    data = ("\n".join(llm_env_lines(homes, profile)) + "\n").encode("utf-8")
    path = homes.deploy_dir / LLM_ENV_NAME
    if path.is_file() and path.read_bytes() == data:
        return "unchanged"
    atomic_write(path, data, 0o600)
    return "generated"


def wait_healthy(url: str, timeout: float, interval: float) -> tuple[bool, dict[str, dict]]:
    """Bounded wait for /health. A container that exited or turned unhealthy ends the wait early,
    after a grace period (restart policies bounce containers while the database initialises)."""
    start = time.monotonic()
    grace = min(30.0, timeout / 2)
    while True:
        states = container_states(True)
        if http_ok(f"{url}/health"):
            return True, states
        elapsed = time.monotonic() - start
        crashed = any(s["status"] in ("exited", "dead", "absent") or s["health"] == "unhealthy" for s in states.values())
        if elapsed >= timeout or (crashed and elapsed >= grace):
            return False, states
        time.sleep(interval)


def cmd_deploy(args, homes: Homes) -> int:
    cfg, _ = read_user_config(homes)
    port = args.port or configured_port(cfg)
    creds = credentials(homes)
    docker = probe_docker()
    if docker["error"]:
        return refuse("deploy", docker["error"], docker=docker)
    if not docker["compose_v2"]:
        return refuse("deploy", "compose_v2_missing", docker=docker)
    states = container_states(True)
    api_running = states["janitor-honcho-api"]["status"] == "running"
    if not port_free(port) and not api_running:
        return refuse("deploy", "port_busy", port=port)
    env_owner = llm_env_status(homes)
    plan = deriver_plan(creds, env_owner)
    if args.llm != "auto" and env_owner != "user":
        wanted_ok = {"openai": bool(creds["OPENAI_API_KEY"] or creds["LLM_OPENAI_API_KEY"]),
                     "minimax": bool(creds["MINIMAX_API_KEY"] or creds["LLM_ANTHROPIC_API_KEY"])
                     and bool(creds["OPENAI_API_KEY"] or creds["LLM_OPENAI_API_KEY"])}[args.llm]
        plan = {**plan, "profile": args.llm, "llm": wanted_ok, "embeddings": wanted_ok}
    if not plan["llm"]:
        return refuse("deploy", "llm_credential_missing", deriver=plan)
    if not plan["embeddings"]:
        return refuse("deploy", "embeddings_credential_missing", deriver=plan)
    if summarize(states) == "not deployed":
        disk = disk_free(([Path(docker["root_dir"])] if docker["root_dir"] else []) + [homes.root])
        if disk["enough"] is False:
            return refuse("deploy", "disk_low", disk=disk)

    homes.deploy_dir.mkdir(parents=True, exist_ok=True)
    compose = ensure_compose(homes)
    source, source_error = ensure_source(homes)
    if source_error:
        return refuse("deploy", source_error.pop("reason"), **source_error)
    llm_env = ensure_llm_env(homes, plan["profile"]) if plan["profile"] != "user-managed" else "kept-user-file"

    env = dict(os.environ)
    env["JANITOR_HONCHO_PORT"] = str(port)
    compose_file = str(homes.deploy_dir / COMPOSE_NAME)
    hint("docker compose up -d (la primera vez construye la imagen: varios minutos) ...")
    up = run(["docker", "compose", "-f", compose_file, "up", "-d"], timeout=args.build_timeout,
             env=env, cwd=str(homes.deploy_dir))
    if up.returncode != 0:
        return refuse("deploy", "compose_up_failed", log=tail(up.stderr or up.stdout, 40),
                      compose=compose, llm_env=llm_env, source=source)

    url = f"http://127.0.0.1:{port}"
    hint(f"Esperando a que {url}/health responda (máx. {args.timeout}s) ...")
    healthy, states = wait_healthy(url, args.timeout, args.interval)
    doc = {"command": "deploy", "ok": healthy, "url": url, "compose": compose, "llm_env": llm_env,
           "llm_profile": plan["profile"], "source": source, "containers": states,
           "volumes_removed": False}
    if not healthy:
        failing = [n for n, s in states.items() if s["status"] != "running" or s["health"] not in (None, "healthy")]
        failing = failing or ["janitor-honcho-api"]
        doc["reason"] = "health_timeout"
        doc["failing"] = [{"container": n, **states[n],
                           "log_tail": tail((lambda p: (p.stdout or "") + (p.stderr or ""))(
                               run(["docker", "logs", "--tail", "30", n])), 30)} for n in failing]
        hint("Honcho no respondió. Los volúmenes se conservan; re-ejecutar deploy reutiliza los datos.")
    return finish(doc)


