#!/usr/bin/env python3
"""Guided Honcho install for Janitor: preflight, deploy, cloud-login, verify, activate, rollback.

Every command prints ONE JSON document on stdout (``cloud-login`` prints JSON Lines:
one ``device_code`` event, then the result) and human hints in Spanish on stderr.
Secret values are read only to hand them to their destination (the deriver env file,
the Honcho client); they are never printed — output and container logs are redacted.

Homes: ``HERMES_HOME`` is the active profile (``config.yaml``, ``.env``, ``honcho.json``).
The containers are per machine and live under the Janitor root home (``JANITOR_HOME``,
else derived from ``HERMES_HOME``) in ``<root>/docker``. Nothing here runs ``sudo``,
removes a container, or removes / prunes a Docker volume.

Exit codes: 0 ok, 1 refused or failed (``ok: false`` + ``reason``), 2 usage/environment.
"""

