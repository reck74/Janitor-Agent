def is_loopback(url: str | None) -> bool:
    from urllib.parse import urlparse

    host = (urlparse(url or "").hostname or "").lower()
    return host in {"localhost", "127.0.0.1", "::1"}


def read_honcho_json(path: Path) -> dict | None:
    """Parsed JSON object, {} when absent, None when it exists but does not parse."""
    if not path.exists():
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    return data if isinstance(data, dict) else None


def build_candidate(homes: Homes, mode: str, url: str | None, peer_name: str | None, host: str) -> tuple[dict, str]:
    """The honcho.json activation would write. Base: the file upstream resolves today, else the template."""
    status = honcho_json_status(homes)
    base_path = Path(status["resolved"]) if status["resolved"] else None
    base = read_honcho_json(base_path) if base_path else None
    origin = str(base_path) if base else "template"
    if not base:
        base = json.loads(TEMPLATE_HONCHO_JSON.read_text(encoding="utf-8"))
        hosts = base.setdefault("hosts", {})
        if host != "hermes" and "hermes" in hosts:
            hosts[host] = hosts.pop("hermes")
        if peer_name:
            base["peerName"] = peer_name
            hosts.get(host, {})["peerName"] = peer_name
    cfg = json.loads(json.dumps(base))
    hosts = cfg.setdefault("hosts", {})
    template_block = json.loads(TEMPLATE_HONCHO_JSON.read_text(encoding="utf-8")).get("hosts", {}).get("hermes", {})
    block = hosts.setdefault(host, dict(template_block))
    block["enabled"] = True
    if peer_name and not (block.get("peerName") or cfg.get("peerName")):
        cfg["peerName"] = peer_name
    if mode == "local":
        cfg.pop("base_url", None)
        cfg["baseUrl"] = url
        if "baseUrl" in block or "base_url" in block:  # a host-level URL would win over the root one
            block.pop("base_url", None)
            block["baseUrl"] = url
    else:
        if is_loopback(cfg.get("baseUrl")):
            cfg.pop("baseUrl")
        if is_loopback(block.get("baseUrl")):
            block.pop("baseUrl")
    return cfg, origin


def round_trip(config_path: Path, host: str) -> dict:
    """One real call through the provider's own client: get-or-create the AI peer."""
    from plugins.memory.honcho.client import HonchoClientConfig, get_honcho_client, reset_honcho_client

    reset_honcho_client()
    hcfg = HonchoClientConfig.from_global_config(host=host, config_path=config_path)
    if not (hcfg.api_key or hcfg.base_url):
        return {"ok": False, "error": "no_credential", "workspace": hcfg.workspace_id}
    try:
        with quiet_stdout():
            client = get_honcho_client(hcfg)
            peer = client.peer(hcfg.ai_peer)
        return {"ok": True, "workspace": hcfg.workspace_id, "ai_peer": peer.id,
                "user_peer": hcfg.peer_name, "base_url": hcfg.base_url or "(cloud)"}
    except Exception as exc:
        return {"ok": False, "error": REDACT(f"{exc.__class__.__name__}: {exc}")[:400],
                "workspace": hcfg.workspace_id}
    finally:
        reset_honcho_client()


def verify_candidate(homes: Homes, mode: str, url: str | None, peer_name: str | None) -> dict:
    """Prove the service/credential with the config activation would write, without writing it."""
    result: dict = {"mode": mode, "api_health": None, "round_trip": None}
    if mode == "local":
        result["api_health"] = http_ok(f"{url}/health")
        if not result["api_health"]:
            result["ok"] = False
            result["reason"] = "api_unreachable"
            return result
    else:
        creds = credentials(homes)
        status = honcho_json_status(homes)
        if not (creds["HONCHO_API_KEY"] or status["has_api_key"] or status["has_oauth"]):
            result.update(ok=False, reason="cloud_credential_missing")
            return result
        for name in ("HONCHO_BASE_URL", "HONCHO_URL"):  # a loopback env URL would shadow the cloud
            if is_loopback(os.environ.get(name)):
                os.environ.pop(name, None)
    sdk_error = ensure_sdk()
    if sdk_error:
        result.update(ok=False, reason="honcho_sdk_unavailable", error=sdk_error)
        return result
    host = active_host()
    candidate, origin = build_candidate(homes, mode, url, peer_name, host)
    with tempfile.TemporaryDirectory(prefix="janitor-honcho-") as tmp:
        path = Path(tmp) / "honcho.json"
        atomic_write(path, json.dumps(candidate).encode("utf-8"))
        result["round_trip"] = round_trip(path, host)
    result["host"] = host
    result["config_origin"] = origin
    result["ok"] = bool(result["round_trip"]["ok"])
    if not result["ok"]:
        result["reason"] = "round_trip_failed"
    return result


def launcher_gate(homes: Homes, mode: str) -> bool:
    """The janitor launcher refuses to open a session with memory.provider=honcho unless Honcho
    has a credential: HONCHO_API_KEY / HONCHO_BASE_URL, or an apiKey, OAuth grant or baseUrl in
    the honcho.json upstream resolves (janitor/cli.py::_owasp_honcho_fail_safe). Local mode writes
    HONCHO_BASE_URL; cloud mode needs the key in the profile .env or the environment, or an
    apiKey / OAuth grant (`cloud-login`) in honcho.json, which activation carries over."""
    if mode == "local":
        return True
    env = read_env_file(homes.env_file)
    if (env.get("HONCHO_API_KEY") or os.environ.get("HONCHO_API_KEY") or "").strip():
        return True
    status = honcho_json_status(homes)
    return bool(status["has_api_key"] or status["has_oauth"])


def cmd_activate(args, homes: Homes) -> int:
    if not hermes_runtime_available():
        return refuse("activate", "hermes_runtime_missing")
    load_profile_env(homes)
    cfg, cfg_error = read_user_config(homes)
    if cfg_error:
        return refuse("activate", "config_unreadable", error=cfg_error)
    if read_honcho_json(homes.honcho_json) is None:
        return refuse("activate", "honcho_json_unparseable", path=str(homes.honcho_json))
    port = args.port or configured_port(cfg)
    url = f"http://127.0.0.1:{port}" if args.mode == "local" else None
    peer_name = args.peer_name or os.environ.get("USER") or None

    if not launcher_gate(homes, args.mode):
        hint("El lanzador janitor exige una credencial de Honcho (HONCHO_API_KEY, o apiKey/OAuth en honcho.json) con memory.provider=honcho: no se activa.")
        return refuse("activate", "failsafe_would_block")
    verification = verify_candidate(homes, args.mode, url, peer_name)
    if not verification["ok"]:
        hint("Verificación fallida: no se ha tocado config.yaml, .env ni honcho.json.")
        return refuse("activate", "verification_failed", verification=verification)

    previous_provider, previous_present = memory_provider(cfg)
    earlier = load_state(homes)
    reactivation = previous_provider == "honcho" and earlier.get("activated_at") and not earlier.get("rolled_back_at")
    state = {"activated_at": _dt.datetime.now().isoformat(timespec="seconds"), "mode": args.mode, "url": url,
             "previous_provider": previous_provider, "previous_provider_present": previous_present,
             "honcho_json": str(homes.honcho_json), "honcho_json_backup": None,
             "honcho_json_created": not homes.honcho_json.exists(), "env": {}}
    if reactivation:
        # Re-activation (e.g. local -> cloud): rollback must still reach the pre-Honcho state.
        for key in ("previous_provider", "previous_provider_present", "honcho_json_backup", "honcho_json_created"):
            state[key] = earlier.get(key, state[key])
        state["env"] = dict(earlier.get("env") or {})
        previous_provider = state["previous_provider"]
    changed = []

    # 1. honcho.json — back up a file that exists, then write the merged candidate.
    from plugins.memory.honcho.oauth import _config_refresh_lock, _refresh_lock

    candidate, _ = build_candidate(homes, args.mode, url, peer_name, verification["host"])
    run_backup = None
    with _refresh_lock, _config_refresh_lock(homes.honcho_json):
        if homes.honcho_json.exists():
            current = read_honcho_json(homes.honcho_json) or {}
            if current != candidate:
                backup = homes.state_dir / f"honcho.json.bak-{timestamp()}"
                atomic_write(backup, homes.honcho_json.read_bytes())
                run_backup = str(backup)
                state["honcho_json_backup"] = state["honcho_json_backup"] or run_backup
        if read_honcho_json(homes.honcho_json) != candidate:
            atomic_write(homes.honcho_json, (json.dumps(candidate, indent=2) + "\n").encode("utf-8"))
            changed.append(str(homes.honcho_json))

    # 2. .env through Hermes' own writer (same code as `janitor config set KEY VALUE`).
    from hermes_cli.config import remove_env_value, save_env_value

    env_now = read_env_file(homes.env_file).get("HONCHO_BASE_URL")
    with quiet_stdout():
        if args.mode == "local" and env_now != url:
            save_env_value("HONCHO_BASE_URL", url)
            first = state["env"].get("HONCHO_BASE_URL", {"previous": env_now})
            state["env"]["HONCHO_BASE_URL"] = {"previous": first["previous"], "written": url}
            changed.append(f"{homes.env_file}: HONCHO_BASE_URL")
        elif args.mode == "cloud" and is_loopback(env_now):
            remove_env_value("HONCHO_BASE_URL")
            first = state["env"].get("HONCHO_BASE_URL", {"previous": env_now})
            state["env"]["HONCHO_BASE_URL"] = {"previous": first["previous"], "written": None}
            changed.append(f"{homes.env_file}: HONCHO_BASE_URL (eliminada)")

    # 3. memory.provider through `janitor config set` (hermes_cli.config.set_config_value).
    if memory_provider(cfg)[0] != "honcho":
        from hermes_cli.config import set_config_value

        with quiet_stdout():
            set_config_value("memory.provider", "honcho")
        changed.append(f"{homes.config_file}: memory.provider=honcho")
    save_state(homes, state)

    after = verify_active(homes)
    return finish({"command": "activate", "ok": True, "mode": args.mode, "changed": changed,
                   "previous_provider": previous_provider or "(memoria integrada)",
                   "honcho_json_backup": run_backup, "verification": verification,
                   "post_check": after, "takes_effect": "next_session", "state_file": str(homes.state_file)})


def verify_active(homes: Homes) -> dict:
    """Check the configuration on disk as the provider will read it next session."""
    cfg, _ = read_user_config(homes)
    provider, _ = memory_provider(cfg)
    out: dict = {"memory_provider": provider}
    if ensure_sdk():
        out.update(ok=False, reason="honcho_sdk_unavailable")
        return out
    from plugins.memory.honcho.client import HonchoClientConfig, resolve_config_path

    host = active_host()
    path = resolve_config_path()
    hcfg = HonchoClientConfig.from_global_config(host=host, config_path=path)
    if hcfg.base_url:
        out["api_health"] = http_ok(f"{hcfg.base_url.rstrip('/')}/health")
    out["config_path"] = str(path)
    out["round_trip"] = round_trip(path, host)
    out["launcher_gate"] = launcher_gate(homes, "local" if is_loopback(hcfg.base_url) else "cloud")
    out["ok"] = provider == "honcho" and out["round_trip"]["ok"] and out["launcher_gate"]
    return out


def cmd_verify(args, homes: Homes) -> int:
    if not hermes_runtime_available():
        return refuse("verify", "hermes_runtime_missing")
    load_profile_env(homes)
    if args.mode:
        cfg, _ = read_user_config(homes)
