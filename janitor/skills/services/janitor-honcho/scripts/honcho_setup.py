def cmd_rollback(args, homes: Homes) -> int:
    if not hermes_runtime_available():
        return refuse("rollback", "hermes_runtime_missing")
    load_profile_env(homes)
    state = load_state(homes)
    if not state.get("activated_at"):
        return refuse("rollback", "no_activation_record", state_file=str(homes.state_file))
    from hermes_cli.config import remove_env_value, save_env_value, set_config_value, unset_config_value

    restored = []
    cfg, _ = read_user_config(homes)
    current, _ = memory_provider(cfg)
    with quiet_stdout():
        if current == "honcho":
            if state.get("previous_provider_present"):
                set_config_value("memory.provider", state.get("previous_provider") or "")
            else:
                unset_config_value("memory.provider")
            restored.append(f"memory.provider={state.get('previous_provider') or '(memoria integrada)'}")
        env_change = (state.get("env") or {}).get("HONCHO_BASE_URL")
        if env_change and read_env_file(homes.env_file).get("HONCHO_BASE_URL") == env_change.get("written"):
            if env_change.get("previous"):
                save_env_value("HONCHO_BASE_URL", env_change["previous"])
            else:
                remove_env_value("HONCHO_BASE_URL")
            restored.append("HONCHO_BASE_URL")
    stopped = None
    if args.stop_containers:
        docker = probe_docker()
        if docker["daemon"]:
            present = [n for n, s in container_states(True).items() if s["status"] == "running"]
            stopped = run(["docker", "stop", *present]).returncode == 0 if present else True
        else:
            stopped = False
    state["rolled_back_at"] = _dt.datetime.now().isoformat(timespec="seconds")
    save_state(homes, state)
    kept = [f"volúmenes Docker {', '.join(VOLUMES)} (datos de Honcho)", str(homes.honcho_json),
            str(homes.deploy_dir), str(homes.source_dir), str(homes.state_dir)]
    if state.get("honcho_json_backup"):
        kept.append(state["honcho_json_backup"])
    return finish({"command": "rollback", "ok": True, "restored": restored, "containers_stopped": stopped,
                   "volumes_removed": False, "kept_on_disk": kept, "takes_effect": "next_session"})


def cmd_cloud_login(args, homes: Homes) -> int:
    """RFC 8628 device-code sign-in to Honcho Cloud. The grant goes straight into the profile's
    honcho.json (the same writer `hermes memory setup honcho` uses); nothing passes through chat."""
    if not hermes_runtime_available():
        return refuse("cloud-login", "hermes_runtime_missing")
    load_profile_env(homes)
    if read_honcho_json(homes.honcho_json) is None:
        return refuse("cloud-login", "honcho_json_unparseable", path=str(homes.honcho_json))
    if (sdk_error := ensure_sdk()):
        return refuse("cloud-login", "honcho_sdk_unavailable", error=sdk_error)
    from plugins.memory.honcho import oauth
    from plugins.memory.honcho.oauth_flow import (
        DeviceFlowError, poll_for_token, request_device_code, resolve_endpoints, supports_device_login,
    )

    endpoints = resolve_endpoints(environment="production", base_url="")
    if not supports_device_login(endpoints):
        return refuse("cloud-login", "device_login_unsupported")
    try:
        device = request_device_code(endpoints, source="hermes-cli")
    except DeviceFlowError as exc:
        return refuse("cloud-login", "device_code_request_failed", error=str(exc.error))
    print(json.dumps({"event": "device_code", "verification_uri": device.verification_uri,
                      "user_code": device.user_code, "verification_uri_complete": device.verification_uri_complete,
                      "expires_in": device.expires_in}), flush=True)
    backup = None
    if homes.honcho_json.exists():
        backup = homes.state_dir / f"honcho.json.bak-{timestamp()}"
        atomic_write(backup, homes.honcho_json.read_bytes())
    try:
        grant = poll_for_token(endpoints, device)
    except DeviceFlowError as exc:
        return refuse("cloud-login", "device_login_failed", error=str(exc.error))
    REDACT.add(*(str(v) for v in grant.values() if isinstance(v, str)))
    oauth.install_grant(homes.honcho_json, active_host(), grant, client_id=endpoints.client_id,
                        token_endpoint=endpoints.token_url, apply_config=False)
    return finish({"command": "cloud-login", "ok": True, "honcho_json": str(homes.honcho_json),
                   "honcho_json_backup": str(backup) if backup else None,
                   "launcher_gate": launcher_gate(homes, "cloud")})


