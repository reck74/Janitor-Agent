#!/usr/bin/env python3
"""Guided self-hosted Firecrawl for Janitor: preflight, deploy, verify, activate, rollback, stop.

Every command prints ONE JSON document on stdout and Spanish hints on stderr. The stack
credentials (Postgres, RabbitMQ, Bull) are generated here and live only in
``<root>/docker/firecrawl.env`` (0600); nothing from the profile ``.env`` reaches the
containers, and no secret value is ever printed.

Homes: ``HERMES_HOME`` is the active profile (``config.yaml``, ``.env``). The containers are
per machine and live under the Janitor root home (``JANITOR_HOME``, else derived from
``HERMES_HOME``) in ``<root>/docker``. Nothing here runs ``sudo``, removes a container, or
removes / prunes a Docker volume.

Exit codes: 0 ok, 1 refused or failed (``ok: false`` + ``reason``), 2 usage/environment.
"""

