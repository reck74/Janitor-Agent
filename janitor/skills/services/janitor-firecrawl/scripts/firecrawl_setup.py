# ── output ────────────────────────────────────────────────────────────────


class Redactor:
    """Replaces every known secret value with ``***`` in anything we print."""

    def __init__(self) -> None:
        self.values: set[str] = set()

    def add(self, *values: str | None) -> None:
        self.values.update(v for v in values if v and len(v) >= 6)

    def __call__(self, text: str) -> str:
        for value in sorted(self.values, key=len, reverse=True):
            text = text.replace(value, "***")
        return text


REDACT = Redactor()


def hint(message: str) -> None:
    print(REDACT(message), file=sys.stderr, flush=True)


def finish(doc: dict) -> int:
    doc.setdefault("schema_version", SCHEMA_VERSION)
    print(REDACT(json.dumps(doc, ensure_ascii=False, indent=2, default=str)), flush=True)
    return 0 if doc.get("ok", True) else 1


def refuse(command: str, reason: str, **extra) -> int:
    return finish({"command": command, "ok": False, "reason": reason, **extra})


# ── homes, files ──────────────────────────────────────────────────────────


class Homes:
    def __init__(self, profile: Path, root: Path) -> None:
        self.profile, self.root = profile, root
        self.deploy_dir = root / "docker"
        self.state_dir = profile / "janitor" / "firecrawl"
        self.state_file = self.state_dir / "state.json"
        self.env_file = profile / ".env"
        self.config_file = profile / "config.yaml"


def resolve_homes() -> Homes | None:
    raw = (os.environ.get("HERMES_HOME") or os.environ.get("JANITOR_HOME") or "").strip()
    if not raw:
        return None
    profile = Path(raw).expanduser()
    root_raw = (os.environ.get("JANITOR_HOME") or "").strip()
    if root_raw:
        root = Path(root_raw).expanduser()
    elif profile.parent.name == "profiles":
        root = profile.parent.parent
    else:
        root = profile
    return Homes(profile, root)


def read_env_file(path: Path) -> dict[str, str]:
    """Minimal dotenv reader (KEY=VALUE, optional ``export``, quotes). Values stay in memory."""
    values: dict[str, str] = {}
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError:
        return values
    for line in lines:
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        key = key.strip()
        if key.startswith("export "):
            key = key[len("export "):].strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        values[key] = value
    return values


def register_secrets(values: dict[str, str]) -> None:
    REDACT.add(*(v for k, v in values.items() if any(w in k.upper() for w in SECRET_WORDS)))


def sha256_file(path: Path) -> str | None:
    try:
        return hashlib.sha256(path.read_bytes()).hexdigest()
    except OSError:
        return None


def atomic_write(path: Path, data: bytes, mode: int = 0o600) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=str(path.parent), prefix=f".{path.name}.")
    try:
        with os.fdopen(fd, "wb") as fh:
            fh.write(data)
        os.chmod(tmp, mode)
        os.replace(tmp, path)
    except BaseException:
        with contextlib.suppress(OSError):
            os.unlink(tmp)
        raise


def timestamp() -> str:
    return _dt.datetime.now().strftime("%Y%m%d-%H%M%S")


def load_state(homes: Homes) -> dict:
    try:
        data = json.loads(homes.state_file.read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else {}
    except (OSError, ValueError):
        return {}


def save_state(homes: Homes, state: dict) -> None:
    atomic_write(homes.state_file, json.dumps(state, indent=2).encode("utf-8"))


def read_user_config(homes: Homes) -> tuple[dict | None, str | None]:
    """Raw config.yaml (not merged with defaults). (None, reason) when it cannot be read."""
    if not homes.config_file.exists():
        return {}, None
    try:
        import yaml
    except ImportError:
        return None, "pyyaml_unavailable"
    try:
        data = yaml.safe_load(homes.config_file.read_text(encoding="utf-8")) or {}
    except (OSError, yaml.YAMLError) as exc:
        return None, f"config_unreadable: {exc.__class__.__name__}"
    return (data if isinstance(data, dict) else {}), None


def web_section(cfg: dict | None) -> dict:
    web = (cfg or {}).get("web")
    return web if isinstance(web, dict) else {}


def configured_port(cfg: dict | None) -> int:
    for path in (("skills", "config", "janitor", "firecrawl_port"), ("skills", "config", "janitor.firecrawl_port"),
                 ("janitor", "firecrawl_port")):
        node = cfg or {}
        for key in path:
            node = node.get(key) if isinstance(node, dict) else None
        if isinstance(node, int) and 0 < node < 65536:
            return node
    return DEFAULT_PORT


# ── tools on PATH, probes (read-only) ─────────────────────────────────────


def which(name: str) -> str | None:
    """PATH lookup without shutil.which (an upstream guard scans janitor/ for it)."""
    for entry in os.environ.get("PATH", "").split(os.pathsep):
        if not entry:
            continue
        candidate = Path(entry) / name
        if candidate.is_file() and os.access(candidate, os.X_OK):
            return str(candidate)
    return None


def run(argv: list[str], *, timeout: float = 60, env: dict | None = None, cwd: str | None = None):
    try:
        return subprocess.run(argv, capture_output=True, text=True, timeout=timeout, env=env, cwd=cwd, check=False)
    except FileNotFoundError:
        return subprocess.CompletedProcess(argv, 127, "", f"{argv[0]}: not found")
    except subprocess.TimeoutExpired:
        return subprocess.CompletedProcess(argv, 124, "", f"{argv[0]}: timed out after {timeout}s")


def tail(text: str, lines: int = 30) -> list[str]:
    return [REDACT(line) for line in (text or "").splitlines()[-lines:]]


def os_release() -> dict[str, str]:
    data: dict[str, str] = {}
    with contextlib.suppress(OSError):
        for line in Path("/etc/os-release").read_text(encoding="utf-8").splitlines():
            key, _, value = line.partition("=")
            data[key.strip()] = value.strip().strip('"')
    return data


def docker_install_hint() -> dict[str, str]:
    """Exact install command for the user to run. Suggestion only: never executed here."""
    if sys.platform == "darwin":
        return {"distro": "macos", "command": "brew install --cask docker  # o Docker Desktop: https://docs.docker.com/desktop/"}
    rel = os_release()
    ids = {rel.get("ID", "").lower(), *rel.get("ID_LIKE", "").lower().split()}
    group = "sudo usermod -aG docker $USER  # cierra sesión y vuelve a entrar"
    if "arch" in ids:
        cmd = f"sudo pacman -S --needed docker docker-compose && sudo systemctl enable --now docker.service && {group}"
    elif ids & {"opensuse", "suse", "sles"}:
        cmd = f"sudo zypper install docker docker-compose && sudo systemctl enable --now docker && {group}"
    else:
        cmd = f"curl -fsSL https://get.docker.com -o get-docker.sh && sudo sh get-docker.sh && {group}"
    return {"distro": rel.get("ID", "linux") or "linux", "command": cmd}


def probe_docker() -> dict:
    out = {"cli": False, "daemon": False, "compose_v2": False, "compose_version": None,
           "root_dir": None, "error": None, "install_hint": None, "fix_hint": None}
    if not which("docker"):
        out.update(error="docker_missing", install_hint=docker_install_hint())
        return out
    out["cli"] = True
    info = run(["docker", "info", "--format", "{{.DockerRootDir}}"], timeout=20)
    if info.returncode != 0:
        if "permission denied" in (info.stderr or "").lower():
            out.update(error="docker_permission_denied",
                       fix_hint="sudo usermod -aG docker $USER  # cierra sesión y vuelve a entrar")
        else:
            out.update(error="docker_daemon_down", fix_hint="sudo systemctl start docker")
    else:
        out["daemon"] = True
        out["root_dir"] = (info.stdout or "").strip() or None
    compose = run(["docker", "compose", "version", "--short"], timeout=20)
    if compose.returncode == 0 and (compose.stdout or "").strip():
        version = compose.stdout.strip().lstrip("v")
        out["compose_version"] = version
        major = version.split(".", 1)[0]
        out["compose_v2"] = major.isdigit() and int(major) >= 2
    return out


def port_free(port: int) -> bool:
    sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    try:
        sock.bind(("127.0.0.1", port))
        return True
    except OSError:
        return False
    finally:
        sock.close()


def http_status(url: str, *, data: bytes | None = None, timeout: float = 5.0) -> tuple[int | None, bytes]:
    """(status, body) of one request to a URL we built; (None, b"") when nothing answers."""
    req = urllib.request.Request(url, data=data, method="POST" if data is not None else "GET",
                                 headers={"Content-Type": "application/json"} if data is not None else {})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:  # noqa: S310 — loopback URL we built
            return resp.status, resp.read(65536)
    except urllib.error.HTTPError as exc:
        return exc.code, b""
    except (urllib.error.URLError, OSError, ValueError):
        return None, b""


def liveness(url: str, timeout: float = 5.0) -> dict:
    status, _ = http_status(f"{url}{LIVENESS_PATH}", timeout=timeout)
    return {"url": f"{url}{LIVENESS_PATH}", "status": status, "responds": status is not None and 200 <= status < 300}


def container_states(docker_ok: bool) -> dict[str, dict]:
    states: dict[str, dict] = {}
    for name in CONTAINERS:
        if not docker_ok:
            states[name] = {"status": "unknown", "health": None}
            continue
        proc = run(["docker", "inspect", "-f", "{{.State.Status}}|{{if .State.Health}}{{.State.Health.Status}}{{end}}", name])
        if proc.returncode != 0:
            states[name] = {"status": "absent", "health": None}
            continue
        status, _, health = (proc.stdout or "").strip().partition("|")
        states[name] = {"status": status or "unknown", "health": health or None}
    return states


def summarize(states: dict[str, dict]) -> str:
    values = {s["status"] for s in states.values()}
    if values == {"running"}:
        return "running"
    if values == {"absent"}:
        return "not deployed"
    if "unknown" in values:
        return "unknown"
    return "degraded" if "running" in values else "stopped"


def disk_free(paths: list[Path]) -> dict:
    for path in paths:
        probe = path
        while not probe.exists() and probe != probe.parent:
            probe = probe.parent
        try:
            usage = shutil.disk_usage(probe)
        except OSError:
            continue
        free_gb = round(usage.free / 1024 ** 3, 1)
        return {"path": str(probe), "free_gb": free_gb, "required_gb": MIN_FREE_GB, "enough": free_gb >= MIN_FREE_GB}
    return {"path": None, "free_gb": None, "required_gb": MIN_FREE_GB, "enough": None}


def total_ram_gb() -> float | None:
    with contextlib.suppress(OSError, ValueError, IndexError):
        for line in Path("/proc/meminfo").read_text(encoding="utf-8").splitlines():
            if line.startswith("MemTotal:"):
                return round(int(line.split()[1]) / 1024 ** 2, 1)
    return None


def compose_status(homes: Homes) -> dict:
    deployed = homes.deploy_dir / COMPOSE_NAME
    digest = sha256_file(deployed)
    if digest is None:
        return {"deployed": False, "owner": None}
    stamp = homes.deploy_dir / STAMP_NAME
    ours = digest == sha256_file(SHIPPED_COMPOSE) or digest in LEGACY_COMPOSE_SHA256 or (
        stamp.is_file() and stamp.read_text(encoding="utf-8").strip() == digest)
    return {"deployed": True, "owner": "janitor" if ours else "user"}


def stack_env_status(homes: Homes) -> dict:
    path = homes.deploy_dir / STACK_ENV_NAME
    if not path.is_file():
        return {"present": False, "missing_keys": []}
    values = read_env_file(path)
    register_secrets(values)
    return {"present": True, "missing_keys": [k for k in STACK_ENV_REQUIRED if not values.get(k)]}


def activation_status(homes: Homes, cfg: dict | None, url: str) -> dict:
    """How the profile's web tools would reach Firecrawl. Presence and equality only, never values."""
    env = read_env_file(homes.env_file)
    register_secrets(env)
    web = web_section(cfg)
    current_url = (env.get("FIRECRAWL_API_URL") or "").rstrip("/")
    overrides = {k: web.get(k) for k in ("search_backend", "extract_backend")
                 if str(web.get(k) or "").strip() and str(web.get(k)).strip().lower() != "firecrawl"}
    backend = str(web.get("backend") or "").strip().lower()
    return {
        "web_backend": backend or None,
        "per_capability_overrides": overrides,
        "api_url_set": bool(current_url),
        "api_url_is_local_instance": current_url == url,
        "cloud_api_key_present": bool((env.get("FIRECRAWL_API_KEY") or "").strip()),
        "active": backend == "firecrawl" and current_url == url and not overrides,
    }


# ── preflight ───────────────────────────────────────────────────────────


def cmd_preflight(args, homes: Homes) -> int:
    cfg, cfg_error = read_user_config(homes)
    port = args.port or configured_port(cfg)
    url = f"http://127.0.0.1:{port}"
    docker = probe_docker()
    docker_ok = docker["daemon"]
    states = container_states(docker_ok)
    service_state = summarize(states)
    api_running = states[API_CONTAINER]["status"] == "running"
    probe = liveness(url) if api_running else {"url": f"{url}{LIVENESS_PATH}", "status": None, "responds": False}
    free = port_free(port)
    owner = None if free else (API_CONTAINER if api_running else "other")
    disk = disk_free(([Path(docker["root_dir"])] if docker["root_dir"] else []) + [homes.root])
    ram = total_ram_gb()
    volumes = {v: run(["docker", "volume", "inspect", v]).returncode == 0 for v in VOLUMES} if docker_ok else \
        {v: None for v in VOLUMES}
    stack_env = stack_env_status(homes)
    activation = activation_status(homes, cfg, url)

    blockers = []
    if docker["error"]:
        blockers.append(docker["error"])
    elif not docker["compose_v2"]:
        blockers.append("compose_v2_missing")
    if owner == "other":
        blockers.append("port_busy")
    if disk["enough"] is False and service_state == "not deployed":
        blockers.append("disk_low")
    if stack_env["missing_keys"]:
        blockers.append("stack_env_incomplete")
    warnings = ["low_memory"] if ram is not None and ram < MIN_RAM_GB else []

    if activation["active"] and probe["responds"]:
        recommendation = "already-active"
    elif probe["responds"]:
        recommendation = "activate"
    elif blockers:
        recommendation = "blocked"
    else:
        recommendation = "deploy"

    for blocker in blockers:
        hint(f"bloqueado por {blocker}")
    return finish({
        "command": "preflight", "ok": True,
        "home": {"profile": str(homes.profile), "root": str(homes.root), "deploy_dir": str(homes.deploy_dir)},
        "docker": docker,
        "port": {"number": port, "free": free, "owner": owner},
        "disk": disk,
        "memory": {"total_gb": ram, "recommended_gb": MIN_RAM_GB},
        "service": {"state": service_state, "url": url, "liveness": probe, "containers": states,
                    "volumes": volumes, "compose": compose_status(homes), "stack_env": stack_env},
        "config": {"path": str(homes.config_file), "error": cfg_error},
        "activation": activation,
        "activation_record": bool(load_state(homes).get("activated_at")),
        "blockers": blockers, "warnings": warnings,
        "recommendation": recommendation,
    })


# ── deploy ────────────────────────────────────────────────────────────────


def ensure_compose(homes: Homes) -> str:
    deployed = homes.deploy_dir / COMPOSE_NAME
    stamp = homes.deploy_dir / STAMP_NAME
    shipped = SHIPPED_COMPOSE.read_bytes()
    shipped_sha = hashlib.sha256(shipped).hexdigest()
    status = compose_status(homes)
    if status["deployed"] and status["owner"] == "user":
        hint(f"{deployed} tiene cambios del usuario: se conserva tal cual.")
        return "kept-user-file"
    if status["deployed"] and sha256_file(deployed) == shipped_sha:
        atomic_write(stamp, shipped_sha.encode(), 0o644)
        return "unchanged"
    if status["deployed"]:
        backup = homes.deploy_dir / f"{COMPOSE_NAME}.bak-{timestamp()}"
        shutil.copy2(deployed, backup)
        hint(f"Compose anterior respaldado en {backup}")
    atomic_write(deployed, shipped, 0o644)
    atomic_write(stamp, shipped_sha.encode(), 0o644)
    return "updated" if status["deployed"] else "installed"


def ensure_stack_env(homes: Homes) -> str:
    """Stack-internal credentials only. An existing file is never regenerated (the Postgres
    volume was initialised with its password)."""
    path = homes.deploy_dir / STACK_ENV_NAME
    if path.is_file():
        return "kept"
    pg, bull, rabbit = secrets.token_hex(16), secrets.token_hex(24), secrets.token_hex(16)
    REDACT.add(pg, bull, rabbit)
    lines = [
        STACK_ENV_MARKER,
        "# Credenciales internas del stack (Postgres, RabbitMQ, Bull). Nada del .env del perfil.",
        "# POSTGRES_DB debe ser postgres: la imagen nuq-postgres fija cron.database_name=postgres.",
        "POSTGRES_USER=postgres", f"POSTGRES_PASSWORD={pg}", "POSTGRES_DB=postgres",
        "USE_DB_AUTHENTICATION=false",
        f"BULL_AUTH_KEY={bull}",
        "RABBITMQ_DEFAULT_USER=firecrawl", f"RABBITMQ_DEFAULT_PASS={rabbit}",
        f"NUQ_RABBITMQ_URL=amqp://firecrawl:{rabbit}@firecrawl-rabbitmq:5672",
        "NUM_WORKERS_PER_QUEUE=8", "CRAWL_CONCURRENT_REQUESTS=10",
    ]
    atomic_write(path, ("\n".join(lines) + "\n").encode("utf-8"), 0o600)
    return "generated"


def wait_live(url: str, timeout: float, interval: float) -> tuple[bool, dict[str, dict]]:
    """Bounded wait for liveness. A crashed container ends the wait early after a grace period."""
    start = time.monotonic()
    grace = min(60.0, timeout / 2)
    while True:
        states = container_states(True)
        if liveness(url, timeout=3)["responds"]:
            return True, states
        elapsed = time.monotonic() - start
        crashed = any(s["status"] in ("exited", "dead", "absent") or s["health"] == "unhealthy" for s in states.values())
        if elapsed >= timeout or (crashed and elapsed >= grace):
            return False, states
        time.sleep(interval)


def cmd_deploy(args, homes: Homes) -> int:
    cfg, _ = read_user_config(homes)
    port = args.port or configured_port(cfg)
    docker = probe_docker()
    if docker["error"]:
        return refuse("deploy", docker["error"], docker=docker)
    if not docker["compose_v2"]:
        return refuse("deploy", "compose_v2_missing", docker=docker)
    states = container_states(True)
    if not port_free(port) and states[API_CONTAINER]["status"] != "running":
        return refuse("deploy", "port_busy", port=port)
    stack_env = stack_env_status(homes)
    if stack_env["missing_keys"]:
        return refuse("deploy", "stack_env_incomplete", path=str(homes.deploy_dir / STACK_ENV_NAME),
                      missing_keys=stack_env["missing_keys"])
    if summarize(states) == "not deployed":
        disk = disk_free(([Path(docker["root_dir"])] if docker["root_dir"] else []) + [homes.root])
        if disk["enough"] is False:
            return refuse("deploy", "disk_low", disk=disk)

    homes.deploy_dir.mkdir(parents=True, exist_ok=True)
    compose = ensure_compose(homes)
    env_file = ensure_stack_env(homes)
    env = dict(os.environ)
    env["JANITOR_FIRECRAWL_PORT"] = str(port)
    hint("docker compose up -d (la primera vez descarga ~5 GB de imágenes) ...")
    up = run(["docker", "compose", "-f", str(homes.deploy_dir / COMPOSE_NAME), "up", "-d"],
             timeout=args.pull_timeout, env=env, cwd=str(homes.deploy_dir))
    if up.returncode != 0:
        return refuse("deploy", "compose_up_failed", log=tail(up.stderr or up.stdout, 40),
                      compose=compose, stack_env=env_file)

    url = f"http://127.0.0.1:{port}"
    hint(f"Esperando a que {url}{LIVENESS_PATH} responda (máx. {args.timeout}s) ...")
    live, states = wait_live(url, args.timeout, args.interval)
    doc = {"command": "deploy", "ok": live, "url": url, "compose": compose, "stack_env": env_file,
           "containers": states, "volumes_removed": False, "activated": False}
    if not live:
        failing = [n for n, s in states.items() if s["status"] != "running" or s["health"] not in (None, "healthy")]
        failing = failing or [API_CONTAINER]
        doc["reason"] = "health_timeout"
        doc["failing"] = [{"container": n, **states[n], "log_tail": tail(
            (lambda p: (p.stdout or "") + (p.stderr or ""))(run(["docker", "logs", "--tail", "30", n])), 30)}
            for n in failing]
        hint("Firecrawl no respondió. Los volúmenes se conservan; re-ejecutar deploy reutiliza los datos.")
    return finish(doc)


# ── verify ────────────────────────────────────────────────────────────────


def cmd_verify(args, homes: Homes) -> int:
    cfg, _ = read_user_config(homes)
    port = args.port or configured_port(cfg)
    url = f"http://127.0.0.1:{port}"
    probe = liveness(url)
    doc = {"command": "verify", "url": url, "liveness": probe,
           "activation": activation_status(homes, cfg, url), "scrape": None}
    if not probe["responds"]:
        doc.update(ok=False, reason="service_unreachable")
        return finish(doc)
    if args.scrape:
        payload = json.dumps({"url": args.scrape, "formats": ["markdown"]}).encode("utf-8")
        status, body = http_status(f"{url}{SCRAPE_PATH}", data=payload, timeout=args.scrape_timeout)
        try:
            parsed = json.loads(body or b"{}")
        except ValueError:
            parsed = {}
        data = parsed.get("data") if isinstance(parsed, dict) else None
        markdown = (data or {}).get("markdown") if isinstance(data, dict) else None
        ok = status == 200 and isinstance(parsed, dict) and parsed.get("success") is True and bool(markdown)
        doc["scrape"] = {"target": args.scrape, "status": status, "ok": ok,
                         "markdown_chars": len(markdown) if isinstance(markdown, str) else 0}
        if not ok:
            doc.update(ok=False, reason="scrape_failed")
            return finish(doc)
    doc["ok"] = True
    return finish(doc)


# ── activate / rollback (Hermes config writers) ──────────────────────────


def hermes_runtime_available() -> bool:
    if str(REPO_ROOT) not in sys.path:
        sys.path.insert(0, str(REPO_ROOT))
    try:
        import yaml  # noqa: F401
        import hermes_constants  # noqa: F401
        return True
    except ImportError:
        return False


def find_hermes_python() -> str | None:
    for candidate in (REPO_ROOT / ".venv" / "bin" / "python", REPO_ROOT / "venv" / "bin" / "python"):
        if candidate.is_file() and os.access(candidate, os.X_OK):
            return str(candidate)
    return None


def ensure_runtime() -> None:
    """Re-exec under the Hermes interpreter when this one cannot import Hermes."""
    if hermes_runtime_available():
        return
    python = None if os.environ.get(REEXEC_GUARD) else find_hermes_python()
    if python and Path(python).resolve() != Path(sys.executable).resolve():
        os.environ[REEXEC_GUARD] = "1"
        os.execv(python, [python, str(Path(__file__).resolve()), *sys.argv[1:]])


@contextlib.contextmanager
def quiet_stdout():
    """Hermes writers print progress on stdout; keep stdout for our JSON only."""
    with contextlib.redirect_stdout(sys.stderr):
        yield


def hermes_resolution() -> dict:
    """What Hermes' own web layer resolves now (no network). Best effort: private upstream names."""
    try:
        with quiet_stdout():
            import tools.web_tools as wt
            from plugins.web.firecrawl import provider

            direct = provider._get_direct_firecrawl_config()
            return {"ok": True, "search_backend": wt._get_search_backend(), "extract_backend": wt._get_extract_backend(),
                    "api_url": (direct[1].get("api_url") if direct else None)}
    except Exception as exc:  # noqa: BLE001 — diagnostic only; never blocks
        return {"ok": None, "error": f"{exc.__class__.__name__}: {exc}"[:300]}


def cmd_activate(args, homes: Homes) -> int:
    if not hermes_runtime_available():
        return refuse("activate", "hermes_runtime_missing")
    cfg, cfg_error = read_user_config(homes)
    if cfg_error:
        return refuse("activate", "config_unreadable", error=cfg_error)
    port = args.port or configured_port(cfg)
    url = f"http://127.0.0.1:{port}"
    probe = liveness(url)
    if not probe["responds"]:
        hint("Firecrawl local no responde: no se ha tocado config.yaml ni .env.")
        return refuse("activate", "service_unreachable", liveness=probe)

    env_now = (read_env_file(homes.env_file).get("FIRECRAWL_API_URL") or "")
    web = web_section(cfg)
    earlier = load_state(homes)
    state = {"activated_at": _dt.datetime.now().isoformat(timespec="seconds"), "url": url,
             "previous_backend": web.get("backend"), "previous_backend_present": "backend" in web,
             "previous_api_url": env_now or None, "written_api_url": url}
    if earlier.get("activated_at") and not earlier.get("rolled_back_at"):
        for key in ("previous_backend", "previous_backend_present", "previous_api_url"):
            state[key] = earlier.get(key)

    from hermes_cli.config import save_env_value, set_config_value

    changed = []
    with quiet_stdout():
        if env_now.rstrip("/") != url:
            save_env_value("FIRECRAWL_API_URL", url)
            changed.append(f"{homes.env_file}: FIRECRAWL_API_URL={url}")
        if str(web.get("backend") or "").strip().lower() != "firecrawl":
            set_config_value("web.backend", "firecrawl")
            changed.append(f"{homes.config_file}: web.backend=firecrawl")
    save_state(homes, state)
    cfg_after, _ = read_user_config(homes)
    return finish({"command": "activate", "ok": True, "url": url, "changed": changed,
                   "previous_backend": state["previous_backend"] or "(autodetección de Hermes)",
                   "activation": activation_status(homes, cfg_after, url),
                   "hermes_resolution": hermes_resolution(),
                   "takes_effect": "next_session", "state_file": str(homes.state_file)})


def stop_containers() -> bool | None:
    if not probe_docker()["daemon"]:
        return None
    running = [n for n, s in container_states(True).items() if s["status"] == "running"]
    return run(["docker", "stop", *running]).returncode == 0 if running else True


def cmd_rollback(args, homes: Homes) -> int:
    if not hermes_runtime_available():
        return refuse("rollback", "hermes_runtime_missing")
    state = load_state(homes)
    if not state.get("activated_at"):
        return refuse("rollback", "no_activation_record", state_file=str(homes.state_file))
    cfg, cfg_error = read_user_config(homes)
    if cfg_error:
        return refuse("rollback", "config_unreadable", error=cfg_error)
    from hermes_cli.config import remove_env_value, save_env_value, set_config_value, unset_config_value

    restored = []
    with quiet_stdout():
        if str(web_section(cfg).get("backend") or "").strip().lower() == "firecrawl":
            if state.get("previous_backend_present"):
                set_config_value("web.backend", state.get("previous_backend") or "")
            else:
                unset_config_value("web.backend")
            restored.append(f"web.backend={state.get('previous_backend') or '(autodetección de Hermes)'}")
        if read_env_file(homes.env_file).get("FIRECRAWL_API_URL") == state.get("written_api_url"):
            if state.get("previous_api_url"):
                save_env_value("FIRECRAWL_API_URL", state["previous_api_url"])
            else:
                remove_env_value("FIRECRAWL_API_URL")
            restored.append("FIRECRAWL_API_URL")
    stopped = stop_containers() if args.stop_containers else None
    state["rolled_back_at"] = _dt.datetime.now().isoformat(timespec="seconds")
    save_state(homes, state)
    return finish({"command": "rollback", "ok": True, "restored": restored, "containers_stopped": stopped,
                   "volumes_removed": False, "takes_effect": "next_session",
                   "kept_on_disk": [f"volúmenes Docker {', '.join(VOLUMES)}", str(homes.deploy_dir)]})


def cmd_stop(args, homes: Homes) -> int:
    stopped = stop_containers()
    if stopped is None:
        return refuse("stop", "docker_unavailable")
    return finish({"command": "stop", "ok": stopped, "volumes_removed": False,
                   **({} if stopped else {"reason": "docker_stop_failed"})})


