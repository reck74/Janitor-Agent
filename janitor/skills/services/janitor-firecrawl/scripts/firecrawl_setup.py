def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="firecrawl_setup.py", description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("preflight", help="Read-only: what is feasible and what is missing")
    p.add_argument("--port", type=int)
    p = sub.add_parser("deploy", help="Deploy or repair the janitor-firecrawl-* containers")
    p.add_argument("--port", type=int)
    p.add_argument("--timeout", type=float, default=300, help="seconds to wait for liveness after up")
    p.add_argument("--pull-timeout", type=float, default=1800, help="seconds for docker compose up (pull)")
    p.add_argument("--interval", type=float, default=5, help=argparse.SUPPRESS)
    p = sub.add_parser("verify", help="Prove the local instance answers (writes nothing)")
    p.add_argument("--port", type=int)
    p.add_argument("--scrape", metavar="URL", help="also scrape this page through the local instance")
    p.add_argument("--scrape-timeout", type=float, default=90, help=argparse.SUPPRESS)
    p = sub.add_parser("activate", help="Point this profile's web tools at the local instance")
    p.add_argument("--port", type=int)
    p = sub.add_parser("rollback", help="Restore the previous web backend (keeps all data)")
    p.add_argument("--stop-containers", action="store_true")
    sub.add_parser("stop", help="Stop the running containers (keeps volumes)")
    return parser


COMMANDS = {"preflight": cmd_preflight, "deploy": cmd_deploy, "verify": cmd_verify,
            "activate": cmd_activate, "rollback": cmd_rollback, "stop": cmd_stop}


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    homes = resolve_homes()
    if homes is None:
        hint("HERMES_HOME no está definido: ejecútalo desde Janitor (terminal del agente).")
        finish({"command": args.command, "ok": False, "reason": "hermes_home_unset"})
        return 2
    os.environ["HERMES_HOME"] = str(homes.profile)
    if args.command in ("activate", "rollback"):
        ensure_runtime()
    return COMMANDS[args.command](args, homes)


if __name__ == "__main__":
    raise SystemExit(main())
