REPO_ROOT = Path(__file__).resolve().parents[2]
SKILL_DIR = REPO_ROOT / "skills" / "janitor-firecrawl"
SCRIPTS_DIR = SKILL_DIR / "scripts"
COMPOSE_FILE = SCRIPTS_DIR / "firecrawl-compose.yml"
