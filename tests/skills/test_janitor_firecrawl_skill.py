"""
Tests for the janitor-firecrawl skill.

Verifies the deployment artifacts are well-formed and self-consistent,
covering the bugs fixed in `.plans/firecrawl-deploy-fix.md`:

  - deploy.sh exists and is executable, follows the setup-honcho.sh pattern
  - firecrawl-compose.yml uses pre-built images (no broken `build:` paths)
  - Postgres healthcheck uses literal `postgres` user/db (nuq-postgres
    image forces cron.database_name=postgres)
  - The 5 expected services are present
  - The local API key is consistent between deploy.sh and any reference
    in the compose (intentionally `fc janitor-local` with a space)
  - deploy.sh implements `inject_firecrawl_env` (BUG 13 fix)
  - .env.example documents both cloud and self-hosted options

These are pure static checks — no Docker, no network, no subprocess.
Run with: scripts/run_tests.sh tests/skills/test_janitor_firecrawl_skill.py -q
"""
