# ---------------------------------------------------------------------------
# Test 6: deploy.sh hardcodes the local API key matching the compose env
# ---------------------------------------------------------------------------


def test_deploy_sh_uses_consistent_api_key(deploy_text: str) -> None:
    """BUG 13: API key in deploy.sh must be `fc janitor-local` (with space).

    This is the value that ends up both in the env_file's TEST_API_KEY and
    in `~/.janitor/.env`'s FIRECRAWL_API_KEY — they must match exactly or
    Firecrawl returns 401. The space is intentional and matches the
    upstream Firecrawl image default.
    """
    # Variable assignment line in deploy.sh
    m = re.search(r'^FIRECRAWL_LOCAL_API_KEY="([^"]+)"', deploy_text, re.MULTILINE)
    assert m, "FIRECRAWL_LOCAL_API_KEY constant not defined in deploy.sh"
    assert m.group(1) == EXPECTED_LOCAL_API_KEY, (
        f"API key mismatch: expected {EXPECTED_LOCAL_API_KEY!r}, got {m.group(1)!r}"
    )


def test_deploy_sh_does_not_use_hyphenated_key(deploy_text: str) -> None:
    """Sanity: the common-error hyphenated form should not appear anywhere."""
    # Allow it only inside comments; forbid in assignments and string literals
    code_lines = [
        line
        for line in deploy_text.splitlines()
        if line.strip() and not line.strip().startswith("#")
    ]
    code = "\n".join(code_lines)
    assert (
        "fc-janitor-local" not in code
    ), "found `fc-janitor-local` (hyphen) in deploy.sh — must be `fc janitor-local` (space)"


