# ---------------------------------------------------------------------------
# Test 9: .env.example documents both cloud and self-hosted Firecrawl
# ---------------------------------------------------------------------------


def test_env_example_documents_both_firecrawl_options() -> None:
    """BUG 13 doc: .env.example must document cloud API and self-hosted modes."""
    text = ENV_EXAMPLE.read_text()
    # Find the Firecrawl block — from the header line until the next section
    # (a blank line followed by another `# Something` comment for a different
    # service). Lines like `# FIRECRAWL_API_KEY=` look like new sections to a
    # naive `[A-Z]` lookahead, so anchor on the explicit header pattern.
    m = re.search(
        r"^# Firecrawl[^\n]*\n(?:(?!^# FAL\.ai).*\n)*",
        text,
        re.MULTILINE,
    )
    assert m, "Firecrawl section not found in .env.example"
    block = m.group(0)
    assert "FIRECRAWL_API_KEY=" in block, "cloud option (FIRECRAWL_API_KEY) missing"
    assert "FIRECRAWL_API_URL=" in block, "self-hosted option (FIRECRAWL_API_URL) missing"
    assert "127.0.0.1:1974" in block, "default self-hosted URL missing"
    assert "fc janitor-local" in block, "default self-hosted API key missing"


